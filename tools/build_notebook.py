"""Build notebooks/GME_Q1.ipynb from the package sources, so the self-contained
Colab notebook can never drift from the code in src/gme332.

    python tools/build_notebook.py            # write the notebook
    python tools/build_notebook.py --check    # exit 1 if the notebook is out of date
    python tools/build_notebook.py --script out.py   # write the generated code cell only

The code cell is the concatenation of the modules below, with relative imports
removed and the Malik et al. (2016) data file embedded as a string."""
import argparse
import ast
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, "src", "gme332")
NB = os.path.join(ROOT, "notebooks", "GME_Q1.ipynb")
MODULES = ["config", "basis", "exact", "states", "sdp", "dynamics", "certificates",
           "experiment", "device", "figures", "pipeline"]

