def strip_relative_imports(src: str) -> str:
    lines = src.splitlines()
    drop = set()
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.ImportFrom) and node.level:
            drop.update(range(node.lineno - 1, node.end_lineno))
    return "\n".join(l for i, l in enumerate(lines) if i not in drop)


def build_code() -> str:
    version = ast.literal_eval(
        next(l.split("=", 1)[1] for l in open(os.path.join(PKG, "__init__.py"), encoding="utf-8")
             if l.startswith("__version__")).strip())
    parts = [f"# gme332 v{version}, generated by tools/build_notebook.py from src/gme332. Do not edit by hand.\n"]
    csv_text = open(os.path.join(PKG, "data", "malik2016_extended_data_table1.csv"), encoding="utf-8").read()
    for m in MODULES:
        src = open(os.path.join(PKG, m + ".py"), encoding="utf-8").read()
        if m == "experiment":
            old = 'text = resources.files("gme332.data").joinpath(DATA_FILE).read_text(encoding="utf-8")'
            assert src.count(old) == 1, "experiment.py data loader changed; update build_notebook.py"
            src = src.replace(old, "text = _MALIK2016_CSV")
            src = f"_MALIK2016_CSV = {csv_text!r}\n\n" + src
        src = strip_relative_imports(src)
        parts.append(f"# {'=' * 76}\n# {m}.py\n# {'=' * 76}\n{src}\n")
        if m == "figures":   # pipeline calls figures.fig_*; give it a namespace
            parts.append("import types as _types\nfigures = _types.SimpleNamespace(**{k: v for k, v in "
                         "list(globals().items()) if k.startswith('fig_')})\n")
    parts.append('# ' + '=' * 76 + '\n# Entry point\n# ' + '=' * 76 + '\n'
                 'ctx = run_pipeline(settings=Settings(fig_dir="./figures"))\n')
    code = "\n".join(parts)
    ast.parse(code)                                    # must be valid Python
    return code


def notebook(code: str) -> dict:
    def cell(kind, text):
        c = {"cell_type": kind, "metadata": {}, "source": text.splitlines(True)}
        if kind == "code":
            c.update(execution_count=None, outputs=[])
        return c
    return {"cells": [cell("markdown", MARKDOWN), cell("code", PIP), cell("code", code)],
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--script")
    a = ap.parse_args(argv)
    code = build_code()
    if a.script:
        open(a.script, "w", encoding="utf-8").write(code)
        return 0
    text = json.dumps(notebook(code), indent=1, ensure_ascii=False) + "\n"
    if a.check:
        current = open(NB, encoding="utf-8").read() if os.path.exists(NB) else ""
        if current != text:
            print("notebooks/GME_Q1.ipynb is out of date: run python tools/build_notebook.py")
            return 1
        print("notebook up to date")
        return 0
    open(NB, "w", encoding="utf-8").write(text)
    print("wrote", NB)
    return 0


if __name__ == "__main__":
    sys.exit(main())
